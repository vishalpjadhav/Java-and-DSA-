public class Assignment_operator {
    public static void main (String []args){
        int a = 10;

        a += 5;  // 15
        System.out.println(a);
        a -= 2;  // 13
        System.out.println(a);
        a *= 2;  // 26
        System.out.println(a);
        a /= 2;  // 13
        System.out.println(a);
        a %= 5;  // 3
        System.out.println(a);
    }
}
