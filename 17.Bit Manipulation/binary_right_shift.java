public class binary_right_shift {
    public static void main(String[] args) {
        int a = 5;
        System.out.println(a>>1);
        System.out.println(a>>2);
        System.out.println(6>>2);
        System.out.println(6>>1);
        System.out.println(6>>3);
        System.out.println(3 >> 3);
    }
}
