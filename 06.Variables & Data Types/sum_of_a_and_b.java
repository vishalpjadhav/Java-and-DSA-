import java.util.*;
public class sum_of_a_and_b {
    public static void main(String args []){
        Scanner sc = new Scanner(System.in);
        System.out.print("Enter Value Of a :- ");
        int a = sc.nextInt();
        System.out.print("Enter Value Of a :- ");
        int b = sc.nextInt();
        int sum = a + b;
        System.out.println("Sum of "+ a +" and "+ b +" :- "+sum);
    sc.close();
    }
}
