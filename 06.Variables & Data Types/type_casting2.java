public class type_casting2 {
    public static void main(String[] args) {
        int age = 20;
        double salary = 45000.50;
        char grade = 'A';
        boolean passed = true;

        System.out.println(age);
        System.out.println(salary);
        System.out.println(grade);
        System.out.println(passed);
    }
}
